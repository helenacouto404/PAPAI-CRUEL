_cache = {}


def normalizar(texto):
    sem_acento = unicodedata.normalize("NFD", texto)
    return "".join(c for c in sem_acento if unicodedata.category(c) != "Mn").upper()


def _misturar(cor, alvo, f):
    return tuple(int(c + (a - c) * f) for c, a in zip(cor, alvo))


def renderizar(texto, escala=3, cor=(255, 255, 255), contorno=(20, 16, 28)):
    chave = (texto, escala, cor, contorno)
    if chave in _cache:
        return _cache[chave]
    texto = normalizar(texto)
    largura_px = max(1, len(texto) * 6 - 1)
    superficie = pygame.Surface(((largura_px + 2) * escala, 10 * escala), pygame.SRCALPHA)
    claro = _misturar(cor, (255, 255, 255), 0.45)
    escuro = _misturar(cor, (0, 0, 0), 0.32)
    pixels = []
    for i, ch in enumerate(texto):
        glifo = GLIFOS.get(ch, GLIFOS["?"])
        for y, linha in enumerate(glifo):
            for x, p in enumerate(linha):
                if p == "#":
                    pixels.append(((1 + i * 6 + x) * escala, (1 + y) * escala, y))
    if contorno is not None:
        sombra = _misturar(contorno, (0, 0, 0), 0.4)
        for px, py, _ in pixels:
            superficie.fill(sombra, (px - escala, py, escala * 3, escala * 3))
        for px, py, _ in pixels:
            superficie.fill(contorno, (px - escala, py - escala, escala * 3, escala * 3))
    for px, py, y in pixels:
        tom = claro if y <= 1 else escuro if y >= 5 else cor
        superficie.fill(tom, (px, py, escala, escala))
    _cache[chave] = superficie
    return superficie


def largura(texto, escala=3):
    return (len(normalizar(texto)) * 6 + 1) * escala
